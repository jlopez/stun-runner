"""The sound command equates of the 68k tree (M5d, docs/17 section 3; docs/11 section 11).

`data/sound/commands.json` names every value 00-6C the 68010 can send the sound board: `snd_`
and the 68010's own audio-test name, `cmd_03_imm` for 03 (CLAUDE.md M4e, card A9). The build
turns it into `build/68k/sound_commands.asm`, one `name equ $NN` per command, which
`asm/68k/stunrun.asm` includes after `ram.asm`, so the source writes `dc.w snd_tubmus`, not
`dc.w $0A` (`audio_test_list`, data.asm). The equates are constants: values, no address.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

NAME = re.compile(r"(snd|cmd)_[a-z0-9_]+\Z")


def commands(path: Path) -> list[tuple[int, str, str]]:
    """(value, name, audio-test name or "") of every command, in value order; fails on a
    malformed or doubled name or value."""
    raw = json.loads(path.read_text())
    out = []
    for c in raw["commands"]:
        value, name = int(c["value"], 16), str(c["name"])
        if not NAME.match(name) or not 0 <= value <= 0xFF:
            raise ValueError(f"{path}: command {c['value']} {name!r}")
        out.append((value, name, str(c.get("audio_test") or "")))
    out.sort()
    if len({v for v, _, _ in out}) != len(out) or len({n for _, n, _ in out}) != len(out):
        raise ValueError(f"{path}: a value or a name occurs twice")
    return out


def equates_source(path: Path) -> str:
    lines = [
        "; The sound command values: generated by tools/m68k sound-equates from",
        "; data/sound/commands.json (docs/11 section 11, docs/17 section 3). Build output: do not",
        "; edit. A name is snd_ and the 68010's audio-test name (audio_test_list, 05C63C), or",
        "; cmd_03_imm for 03, which the list leaves out.",
    ]
    for value, name, test in commands(path):
        note = f"\t; {test}" if test else "\t; not in the audio test"
        lines.append(f"{name}\tequ\t${value:02X}{note}")
    return "\n".join(lines) + "\n"


def write_equates(commands_json: Path, out: Path) -> bool:
    """Write the include when its text changes; True when it was written."""
    text = equates_source(commands_json)
    if out.exists() and out.read_text() == text:
        return False
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return True
