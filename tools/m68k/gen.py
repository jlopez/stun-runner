"""The one-shot vasm source generator for the 68k image (docs/14-68k-descent.md section 5).

    tools/m68k gen START END [--image build/stunrun-68k.bin] [--classification ...]
                             [--operands ...] [--snapshot data/ida/stunrun-68k.json]
                             [--equates asm/68k/hardware.asm] [--equates-out FILE]
                             [--externals-out FILE] [--incbin PATH] --out FILE

FROZEN SINCE M5c (issue #33, decision C12, docs/16-68k-code.md): it generated the 68k code files
of asm/68k once; those files are hand-maintained source now, and `gen` refuses to write over a
file of asm/68k. It stays for `check-region` (the generator against the image, docs/14
section 6) and for scratch output.

ONE-SHOT SCAFFOLDING. It writes neutral, byte-identical source for a range of the image from the
image, the classification, the operand decisions, the committed IDA snapshot (names and function
starts only, decision C5) and the hardware equates, in the conventions of decision C2. A code leg
runs it once over its region and commits the output, after which the source is the truth: the
generator is frozen and never runs over a hand-edited file.

What each kind becomes:

    code      instructions; flow targets, PC-relative operands and absolute operands in the ROM
              (000000-0BFFFF) as labels, I/O and RAM operands as equates, long immediates as the
              operand decisions say (operands.py); `pea N.w` stays a number (a constant
              in this ROM, issue #29)
    switch    dc.w case-base, one per entry
    pointers  dc.l label (0 and values outside the ROM stay numbers)
    text      dc.b 'string',0
    fill      dcb.b n,0
    data, unknown
              incbin of the image (decision C3: an unexplained blob is never a dc.b wall)

Labels: a name the snapshot has at an address is used verbatim; otherwise `sub_X` where a routine
starts (a call target, an entry with evidence, a vector, a function start of the snapshot),
`loc_X` for another code label that is reached from another scope, `.lX` (a vasm local) for a
code label or a switch table whose every reference lies between the same two global labels,
`tbl_X` for pointer tables (and switch tables that cannot be local), `str_X` for text, `dat_X`
for data, unknown bytes and fill. X is the address in upper-case hex without padding (IDA's
spelling). An operand into the middle of an instruction or table entry is `label+n`.
"""

from __future__ import annotations

import bisect
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from .classify import Classification, Span
from .decode import (
    ABSL,
    ABSW,
    AN,
    CALL,
    IMM,
    IND,
    PCDISP,
    PCINDEX,
    TARGET,
    Insn,
    Operand,
    decode,
    format_insn,
)
from .descent import _abs

ROM_END = 0x0C0000
RAM = 0xFF8000
# where every generated region starts: these anchors are always global labels
REGION_STARTS = {0x000000, 0x000212, 0x012F06, 0x017000, 0x020000, 0x020430, 0x04397E,
                 0x046AEE, 0x060000, 0x0BFE00}
SHORT = "ABS_SHORT"  # macros.asm: subtract from a RAM equate to write it as absolute short
MACRO_FFFF = {IND: "moveb_ffff_ind", ABSL: "moveb_ffff_abs"}
HEADER = """\
; Generated by tools/m68k gen {lo:06X} {hi:06X} (docs/14-68k-descent.md): one-shot scaffolding.
; From here on this source is the truth; the generator is never run over it again.
"""


class GenError(Exception):
    pass


def hexa(a: int) -> str:
    return f"{a:X}"


@dataclass
class Model:
    image: bytes
    cls: Classification
    names: dict[int, str]  # snapshot names below ROM_END
    functions: set[int]  # snapshot function starts
    ram_names: dict[int, str]  # snapshot names of RAM addresses
    io: list[tuple[int, str]]  # I/O equates, sorted
    segments: list[tuple[int, int]]  # I/O segments, an equate + offset stays inside one
    decisions: dict[tuple[int, int], str]
    insns: dict[int, Insn] = field(default_factory=dict)
    span_starts: list[int] = field(default_factory=list)
    refs: dict[int, set[int]] = field(default_factory=dict)  # anchor -> referrer addresses
    anchors: dict[int, str] = field(default_factory=dict)  # anchor -> kind
    labels: dict[int, str] = field(default_factory=dict)
    local: set[int] = field(default_factory=set)
    routine: set[int] = field(default_factory=set)
    equates_file: set[str] = field(default_factory=set)  # names the --equates file defines
    used_names: set[str] = field(default_factory=set)  # labels used by the current generate
    used_equates: dict[str, int] = field(default_factory=dict)  # equates used, by name

    # --- the model of the whole image ---------------------------------------------------------
    def build(self, forced: set[int]) -> None:
        for s in self.cls.spans:
            if s.kind == "code":
                a = s.start
                while a < s.end:
                    insn = decode(self.image, a)
                    assert insn is not None
                    self.insns[a] = insn
                    a += insn.length
        self.span_starts = [s.start for s in self.cls.spans]
        self.routine = {i.target for i in self.insns.values()
                        if i.flow == CALL and i.target is not None}
        self.routine |= set(self.cls.entries) | self.functions
        for s in self.cls.spans:
            if s.kind == "pointers":
                for p in range(s.start, s.end, 4):
                    v = self._long(p)
                    if 0 < v < ROM_END and self.span_of(v).kind == "code":
                        self.routine.add(v)
        # references
        for a, insn in self.insns.items():
            for i, op in enumerate(insn.operands):
                t = self.symbolic_address(insn, i, op)
                if t is not None and t < ROM_END:
                    self._ref(t, a)
        for s in self.cls.spans:
            if s.kind == "switch":
                self._ref(s.base, s.start)
                for k in range((s.end - s.start) // 2):
                    p = s.start + 2 * k
                    e = int.from_bytes(self.image[p : p + 2], "big", signed=True)
                    self._ref((s.base + e) & 0xFFFFFF, p)
            elif s.kind == "pointers":
                for p in range(s.start, s.end, 4):
                    v = self._long(p)
                    if 0 < v < ROM_END:
                        self._ref(v, p)
        # anchors every range needs: span starts, strings, names, functions
        for s in self.cls.spans:
            if s.kind != "fill":
                self.anchors.setdefault(s.start, s.kind)
            if s.kind == "text":
                p = s.start
                while p < s.end:
                    self.anchors.setdefault(p, "text")
                    z = self.image.find(b"\0", p, s.end)
                    p = s.end if z < 0 else z + 1
        for a in list(self.names) + sorted(self.functions) + sorted(forced):
            if a < self.cls.spans[-1].end:
                self.anchors.setdefault(self.anchor_of(a), self.span_of(a).kind)
        self._name(forced)

    def _long(self, p: int) -> int:
        return int.from_bytes(self.image[p : p + 4], "big")

    def span_of(self, a: int) -> Span:
        i = bisect.bisect_right(self.span_starts, a) - 1
        if i < 0 or a >= self.cls.spans[i].end:
            return Span(a, a + 1, "outside")
        return self.cls.spans[i]

    def anchor_of(self, t: int) -> int:
        """The statement start that holds address t: an instruction, a table entry, or t."""
        s = self.span_of(t)
        if s.kind == "code":
            a = t - (t & 1)
            while a not in self.insns:
                a -= 2
            return a
        if s.kind == "switch":
            return t - ((t - s.start) % 2)
        if s.kind == "pointers":
            return t - ((t - s.start) % 4)
        return t

    def _ref(self, t: int, frm: int) -> None:
        a = self.anchor_of(t)
        self.refs.setdefault(a, set()).add(frm)
        self.anchors.setdefault(a, self.span_of(a).kind)

    def symbolic_address(self, insn: Insn, i: int, op: Operand) -> int | None:
        """The address an operand is written as a symbol for, or None for a number."""
        if op.mode in (TARGET, PCDISP, PCINDEX):
            return op.value
        if op.mode == ABSL:
            return op.value if op.value <= 0xFFFFFF else None
        if op.mode == ABSW:
            v = _abs(op)
            if insn.mnemonic == "pea":
                return None
            return v
        if op.mode == IMM and op.size == "l":
            d = self.decisions.get((insn.addr, i))
            if d == "address":
                return op.value
            if insn.mnemonic == "movea" and insn.operands[-1].mode == AN \
                    and ROM_END <= op.value <= 0xFFFFFF:
                return op.value  # an I/O or RAM address into an address register
        return None

    def _name(self, forced: set[int]) -> None:
        candidates = set()
        for a, kind in self.anchors.items():
            if a in self.names:
                self.labels[a] = self.names[a]
            elif kind == "code":
                if a in self.routine:
                    self.labels[a] = f"sub_{hexa(a)}"
                else:
                    candidates.add(a)
            elif kind == "switch":
                candidates.add(a)
            elif kind == "pointers" or kind == "outside" and a >= 0x0BFE00:
                self.labels[a] = f"tbl_{hexa(a)}"
            elif kind == "text":
                self.labels[a] = f"str_{hexa(a)}"
            else:
                self.labels[a] = f"dat_{hexa(a)}"
        # span starts are global, but a switch table and the code after one (the cases)
        prev: Span | None = None
        fixed = set(forced)
        for s in self.cls.spans:
            if s.kind == "code" and not (prev and prev.kind == "switch"):
                fixed.add(s.start)
            prev = s
        for a in candidates & fixed:
            self.labels[a] = (f"loc_{hexa(a)}" if self.anchors[a] == "code"
                              else f"tbl_{hexa(a)}")
        candidates -= fixed
        local = set(candidates)
        while True:
            globals_ = sorted(a for a in self.anchors if a not in local)
            promote = set()
            for a in local:
                sc = _scope(globals_, a)
                if sc is None or any(_scope(globals_, r) != sc for r in self.refs.get(a, ())):
                    promote.add(a)
            if not promote:
                break
            local -= promote
        self.local = local
        for a in candidates:
            kind = self.anchors[a]
            if a in local:
                self.labels[a] = f".l{hexa(a)}"
            else:
                self.labels[a] = f"loc_{hexa(a)}" if kind == "code" else f"tbl_{hexa(a)}"

    # --- symbols ------------------------------------------------------------------------------
    def label_expr(self, t: int) -> str:
        if t >= self.cls.spans[-1].end:
            name = self.names.get(t) or (f"tbl_{hexa(t)}" if t >= 0x0BFE00 else f"dat_{hexa(t)}")
            self.used_names.add(name)
            self.labels.setdefault(t, name)
            return name
        a = self.anchor_of(t)
        name = self.labels[a]
        self.used_names.add(name)
        return name if a == t else f"{name}+{t - a}"

    def equate(self, v: int) -> str:
        """The symbol of an I/O or RAM address: a snapshot name, an I/O equate (plus an offset
        inside the same segment), or a neutral ram_X / io_X; records what it uses."""
        if v in self.ram_names:
            return self._use(self.ram_names[v], v)
        for base, name in reversed(self.io):
            if base <= v:
                if any(lo <= base and v < hi for lo, hi in self.segments):
                    self._use(name, base)
                    return name if v == base else f"{name}+${v - base:X}"
                break
        return self._use(f"ram_{v:X}" if v >= RAM else f"io_{v:X}", v)

    def _use(self, name: str, v: int) -> str:
        if name not in self.equates_file:
            self.used_equates[name] = v
        return name

    def resolve(self, insn: Insn, i: int, op: Operand) -> str | None:
        t = self.symbolic_address(insn, i, op)
        if t is None:
            return None
        if t < ROM_END:
            return self.label_expr(t)
        sym = self.equate(t)
        if op.mode == ABSW:
            if t < RAM:
                raise GenError(f"{insn.addr:06X}: absolute short {t:06X} is not in the RAM")
            return f"({sym}-{SHORT})"
        return sym


def _scope(globals_: list[int], a: int) -> int | None:
    i = bisect.bisect_right(globals_, a) - 1
    return globals_[i] if i >= 0 else None


# --- loading the inputs -------------------------------------------------------------------------


def load_snapshot(path: Path) -> tuple[dict[int, str], set[int], dict[int, str]]:
    j = json.loads(path.read_text())
    names: dict[int, str] = {}
    ram: dict[int, str] = {}
    for n in j["names"]:
        ea = int(n["ea"], 16)
        if ea < ROM_END:
            names[ea] = n["name"]
        elif ea >= 0xFF0000:
            ram[ea] = n["name"]
    functions = {int(f, 16) for f in j["functions"]}
    return names, functions, ram


EQU = re.compile(r"^([A-Za-z_][\w]*)\s*(?:equ|=)\s*\$([0-9A-Fa-f]+)", re.I)


def load_equates(path: Path | None) -> list[tuple[int, str]]:
    """The I/O equates: from a vasm file (`NAME equ $X`), or ida/memory_map.py's IO_68K."""
    if path is None:
        from ida.memory_map import IO_68K

        return sorted((a, n) for a, n, _ in IO_68K)
    out = []
    for line in path.read_text().splitlines():
        m = EQU.match(line.strip())
        if m:
            out.append((int(m.group(2), 16), m.group(1)))
    return sorted(out)


def io_segments() -> list[tuple[int, int]]:
    from ida.memory_map import SEGMENTS_68K

    return [(s.start, s.end) for s in SEGMENTS_68K if s.start >= ROM_END and s.name != "RAM"]


# --- emission -----------------------------------------------------------------------------------


@dataclass
class Output:
    source: str
    equates: dict[str, int]
    externals: dict[str, int]
    stats: dict[str, int]


def _quote(s: bytes) -> str:
    t = s.decode("latin-1")
    if "'" in t and '"' not in t:
        return '"' + t + '"'
    return "'" + t.replace("'", "''") + "'"


def generate(m: Model, lo: int, hi: int, incbin: str) -> Output:
    lines = [HEADER.format(lo=lo, hi=hi)]
    defined: dict[str, int] = {}
    m.used_names = set()
    m.used_equates = {}
    stats = dict.fromkeys(("instructions", "macros", "labels", "locals", "incbin_bytes"), 0)
    lines.append(f"\tassert\t*=${lo:06X},\"generated range does not start at {lo:06X}\"")
    a = lo

    def label(at: int) -> None:
        name = m.labels.get(at)
        if name is None or at not in m.anchors:
            return
        lines.append(f"{name}:")
        defined[name] = at
        stats["labels"] += 1
        if name.startswith("."):
            stats["locals"] += 1

    spans = [s for s in m.cls.spans if s.end > lo and s.start < hi]
    for s in spans:
        a0, a1 = max(s.start, lo), min(s.end, hi)
        if s.kind == "code":
            if a0 not in m.insns:
                raise GenError(f"{a0:06X} is not an instruction start")
            a = a0
            while a < a1:
                insn = m.insns[a]
                if a + insn.length > a1:
                    raise GenError(f"the instruction at {a:06X} crosses {a1:06X}")
                label(a)
                lines.append("\t" + _insn_text(m, insn, stats))
                stats["instructions"] += 1
                a += insn.length
            continue
        cuts = sorted({x for x in m.anchors if a0 <= x < a1} | {a0, a1})
        step = {"switch": 2, "pointers": 4}.get(s.kind, 1)
        for x, y in zip(cuts, cuts[1:], strict=False):
            label(x)
            if s.kind == "switch":
                base = m.label_expr(s.base)
                for p in range(x, y, step):
                    e = int.from_bytes(m.image[p : p + 2], "big", signed=True)
                    lines.append(f"\tdc.w\t{m.label_expr((s.base + e) & 0xFFFFFF)}-{base}")
            elif s.kind == "pointers":
                for p in range(x, y, step):
                    v = m._long(p)
                    expr = m.label_expr(v) if 0 < v < ROM_END else f"${v:X}"
                    lines.append(f"\tdc.l\t{expr}")
            elif s.kind == "text":
                p = x
                while p < y:
                    z = m.image.find(b"\0", p, y)
                    if z < 0:
                        lines.append(f"\tdc.b\t{_quote(m.image[p:y])}")
                        p = y
                    elif z == p:
                        lines.append("\tdc.b\t0")
                        p += 1
                    else:
                        lines.append(f"\tdc.b\t{_quote(m.image[p:z])},0")
                        p = z + 1
            elif s.kind == "fill":
                if any(m.image[x:y]):
                    raise GenError(f"fill {x:06X}-{y:06X} is not zero")
                lines.append(f"\tdcb.b\t{y - x},0")
            else:
                lines.append(f'\tincbin\t"{incbin}",${x:X},${y - x:X}')
                stats["incbin_bytes"] += y - x
    lines.append(f"\tassert\t*=${hi:06X},\"generated range does not end at {hi:06X}\"")
    # externals: every label the source uses that it does not define
    text = "\n".join(lines)
    by_name = {n: a for a, n in m.labels.items()}
    externals: dict[str, int] = {}
    for name in m.used_names - set(defined):
        if name.startswith("."):
            raise GenError(f"the local label {name} is used but not defined in the range")
        externals[name] = by_name[name]
    return Output(text + "\n", dict(m.used_equates), externals, stats)


def _insn_text(m: Model, insn: Insn, stats: dict[str, int]) -> str:
    if insn.mnemonic == "move" and insn.size == "b" and insn.operands[0].mode == IMM \
            and insn.operands[0].raw & 0xFF00:
        dst = insn.operands[1]
        macro = MACRO_FFFF.get(dst.mode)
        if macro is None or insn.operands[0].raw != 0xFFFF:
            raise GenError(f"{insn.addr:06X}: no macro for a byte immediate word "
                           f"with this destination")
        stats["macros"] += 1
        if dst.mode == IND:
            return f"{macro}\t{dst.reg}"
        return f"{macro}\t{m.resolve(insn, 1, dst) or f'${dst.value:X}'}"
    for op in insn.operands:
        if op.mode == IMM and op.size == "b" and op.raw & 0xFF00:
            raise GenError(f"{insn.addr:06X}: a byte immediate word with a high byte, "
                           f"no macro for {insn.mnemonic}")
    return format_insn(insn, m.resolve)


def equates_text(equates: dict[str, int]) -> str:
    lines = ["; Generated by tools/m68k gen: RAM and I/O equates the generated source uses that the",
             "; hardware equates do not define (neutral names unless the IDA snapshot names them).",
             ""]
    for name, v in sorted(equates.items(), key=lambda x: x[1]):
        lines.append(f"{name}\tequ\t${v:X}")
    return "\n".join(lines) + "\n"


def externals_text(externals: dict[str, int]) -> str:
    lines = ["; Generated by tools/m68k gen: labels the generated range uses and does not define",
             "; (scratch assembly of one range alone; in the tree another file defines them).", ""]
    for name, v in sorted(externals.items(), key=lambda x: x[1]):
        lines.append(f"{name}\tequ\t${v:X}")
    return "\n".join(lines) + "\n"
